"""Pilot C run inputs: the pinned harness binary, the task base snapshots, their generated surfaces and
the warm build caches, all below the run output (outside every trial).

The harness under test and the code a task starts from are separate inputs: `auto` is built once
from a snapshot of the harness revision and generates the surface into a copy of each task's base.
Every hook command is then pinned to that binary by absolute path. A resumed run reuses what exists.
"""
import json
import os
from pathlib import Path
import subprocess

import grade_c
import surface_c
import trial_c
from workspace import snapshot


def resolve_revision(repo: Path, revision: str) -> str:
    """The commit SHA a revision names in repo, resolved once at run start."""
    return subprocess.check_output(['git', 'rev-parse', '--verify', '--end-of-options', revision + '^{commit}'],
                                   cwd=repo, text=True).strip()


def build_harness(ctx: dict, repo: Path) -> Path:
    harness = ctx['harness_revision']
    root = ctx['output'] / 'harness' / harness[:12]
    bin_dir = ctx['output'] / 'bin' / ('harness-' + harness[:12])
    if (bin_dir / 'auto').is_file():
        return bin_dir
    snapshot(repo, harness, root / 'tree')
    env = surface_c.generation_env(ctx['base_env'], root / 'home', bin_dir, ctx['tools_dir'])
    env.update(trial_c.go_env(root, ctx['output'] / 'cache' / 'build'))
    surface_c.build_auto(root / 'tree', bin_dir / 'auto', env)
    return bin_dir


def prepare_sources(ctx: dict, tasks: list, repo: Path) -> dict:
    """Per distinct task base: snapshot, surface generated by the harness binary, warm cache."""
    if not ctx['tools_dir'].exists():
        ctx['tools'] = surface_c.link_tools(ctx['tools_dir'], ctx['tool_names'], ctx['base_env'].get('PATH', ''))
    else:
        ctx['tools'] = {p.name: os.path.realpath(p) for p in sorted(ctx['tools_dir'].iterdir())}
    bin_dir = build_harness(ctx, repo)
    sources = {}
    for base in sorted({task['heads']['base'] for task in tasks}):
        root = ctx['output'] / 'sources' / base[:12]
        tree, meta = root / 'tree', root / 'generated.json'
        if not meta.is_file():
            snapshot(repo, base, tree)
            env = surface_c.generation_env(ctx['base_env'], root / 'home', bin_dir, ctx['tools_dir'])
            env.update(trial_c.go_env(root, ctx['output'] / 'cache' / 'build'))
            generated = surface_c.generate_surface(bin_dir / 'auto', tree, root, env)
            generated.update(surface_c.pin_hooks(root / 'surface', bin_dir / 'auto'))
            packages = [t['oracle']['package'] for t in tasks if t['heads']['base'] == base]
            grade_c.warm(tree, packages, root / 'warm-cache', root / 'warm-tmp')
            meta.write_text(json.dumps(generated, indent=2))
        generated = json.loads(meta.read_text())
        sources[base] = {'tree': tree, 'surface': root / 'surface', 'bin_dir': bin_dir, 'generated': generated,
                         'warm_cache': root / 'warm-cache', 'harness_revision': ctx['harness_revision']}
    return sources


def trial_go_version(ctx: dict) -> str:
    """`go version` as a trial runs it: the linked go with GOTOOLCHAIN=local."""
    go = ctx['tools_dir'] / 'go'
    env = {'PATH': str(ctx['tools_dir']) + ':/usr/bin:/bin', 'HOME': str(ctx['output']), 'GOTOOLCHAIN': 'local'}
    return subprocess.check_output([str(go), 'version'], env=env, text=True).strip()
