// The extension runs the checks the Claude Code Stop hooks would, with the
// same switches, and is not written when every check is off.
func TestPrepareStopGateMappings_FollowsTheStopHookSwitches(t *testing.T) {
	t.Parallel()
	off := false
	cases := map[string]struct {
		lang          string
		verify, lang2 *bool
		want          string
	}{
		"both checks":            {"ko", nil, nil, `["stop","language"]`},
		"english skips language": {"en", nil, nil, `["stop"]`},
		"verify stop off":        {"ko", &off, nil, `["language"]`},
		"everything off":         {"en", &off, nil, ""},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			cfg := config.DefaultFullConfig("demo")
			cfg.Language.AIResponses = tc.lang
			cfg.Hooks.VerifyStop, cfg.Hooks.LanguageStop = tc.verify, tc.lang2
			files, err := prepareStopGateMappings(cfg)
			require.NoError(t, err)
			if tc.want == "" {
				assert.Empty(t, files)
				return
			}
			require.Len(t, files, 1)
			assert.Equal(t, ompStopGateTarget, files[0].TargetPath)
			body := string(files[0].Content)
			assert.Contains(t, body, "const CHECKS: string[] = "+tc.want)
			assert.NotContains(t, body, "__AUTOPUS_STOP_CHECKS__")
			assert.True(t, strings.HasPrefix(body, "// Generated by Autopus-ADK."))
		})
	}
}

func TestStopGateTargetIsPruneOwned(t *testing.T) {
	t.Parallel()
	assert.Contains(t, ompExclusivePruneRoots(), ompStopGateTarget)
}

// The context policy opt-in locks .omp/extensions to its managed bridge and
// route (SPEC-OMP-004), so the gate stays out of it.
func TestPrepareStopGateMappings_LeavesTheContextPolicySetAlone(t *testing.T) {
	t.Parallel()
	cfg := optedInOMPContextBridgeConfig()
	cfg.Language.AIResponses = "ko"
	files, err := prepareStopGateMappings(cfg)
	require.NoError(t, err)
	assert.Empty(t, files)
}
