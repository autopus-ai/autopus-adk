// surfaceCutCase is one platform's slice of the surface the verification
// harness stopped installing: a removed route, agent, and rule, at the paths
// v0.50.133 generated and recorded in its manifest.
type surfaceCutCase struct {
	name     string
	manifest string
	removed  []string
	newAdapt func(root string) adapter.PlatformAdapter
}

func surfaceCutCases() []surfaceCutCase {
	return []surfaceCutCase{
		{
			name: "claude-code", manifest: "claude-code",
			removed: []string{
				".claude/skills/auto-plan/SKILL.md",
				".claude/agents/autopus/planner.md",
				".claude/rules/autopus/objective-reasoning.md",
			},
			newAdapt: func(root string) adapter.PlatformAdapter { return claude.NewWithRoot(root) },
		},
		{
			name: "codex", manifest: "codex",
			removed: []string{
				".codex/skills/codex-auto-plan/SKILL.md",
				".codex/agents/planner.toml",
			},
			newAdapt: func(root string) adapter.PlatformAdapter { return codex.NewWithRoot(root) },
		},
		{
			name: "antigravity-cli", manifest: "antigravity-cli",
			removed: []string{
				".gemini/commands/auto/plan.toml",
				".agents/plugins/autopus/agents/planner.md",
				".agents/plugins/autopus/rules/objective-reasoning.md",
			},
			newAdapt: func(root string) adapter.PlatformAdapter { return antigravity.NewWithRoot(root) },
		},
		{
			name: "opencode", manifest: "opencode",
			removed: []string{
				".opencode/commands/auto-plan.md",
				".opencode/agents/planner.md",
				".opencode/rules/autopus/objective-reasoning.md",
			},
			newAdapt: func(root string) adapter.PlatformAdapter {
				return opencode.NewWithRoot(root, opencode.WithCLIVersion("1.18.7"))
			},
		},
		{
			name: "omp", manifest: "omp",
			removed: []string{
				".omp/commands/auto-plan.md",
				".omp/agents/planner.md",
				".omp/rules/autopus-objective-reasoning.md",
			},
			newAdapt: func(root string) adapter.PlatformAdapter { return omp.NewWithRoot(root) },
		},
	}
}

// seedRemovedSurface writes each removed file unmodified and records it in the
// platform manifest, the state a v0.50.133 install leaves behind.
func seedRemovedSurface(t *testing.T, root, manifestName string, paths []string) {
	t.Helper()
	manifest, err := adapter.LoadManifest(root, manifestName)
	require.NoError(t, err)
	require.NotNil(t, manifest)
	for _, rel := range paths {
		body := "generated by v0.50.133: " + rel
		abs := filepath.Join(root, filepath.FromSlash(rel))
		require.NoError(t, os.MkdirAll(filepath.Dir(abs), 0o755))
		require.NoError(t, os.WriteFile(abs, []byte(body), 0o644))
		manifest.Files[rel] = adapter.ManifestFile{Checksum: adapter.Checksum(body), Policy: adapter.OverwriteAlways}
	}
	require.NoError(t, manifest.Save(root))
}

// TestUpdate_PrunesRemovedSurfaceOnEveryPlatform is the upgrade half of the
// verification-harness cut: Update on a v0.50.133 install must delete the
// routes, agents, and rules this release no longer generates, on every
// platform, without asking the user to clean them by hand.
func TestUpdate_PrunesRemovedSurfaceOnEveryPlatform(t *testing.T) {
	t.Parallel()
	for _, tc := range surfaceCutCases() {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			// Given: a fresh install plus the removed surface the old release recorded
			root := t.TempDir()
			cfg := config.DefaultFullConfig("surface-cut")
			_, err := tc.newAdapt(root).Generate(context.Background(), cfg)
			require.NoError(t, err)
			seedRemovedSurface(t, root, tc.manifest, tc.removed)

			// When: the new release updates the install
			_, err = tc.newAdapt(root).Update(context.Background(), cfg)
			require.NoError(t, err)

			// Then: every removed file is gone and no longer recorded
			manifest, err := adapter.LoadManifest(root, tc.manifest)
			require.NoError(t, err)
			for _, rel := range tc.removed {
				_, statErr := os.Stat(filepath.Join(root, filepath.FromSlash(rel)))
				assert.True(t, os.IsNotExist(statErr), "%s survived the update", rel)
				assert.NotContains(t, manifest.Files, rel, "%s is still recorded", rel)
			}
		})
	}
}
