var behaviorBase = map[string]string{"go.mod": redModule, "add.go": redAddBase, "add_test.go": redTestWeak}

func behaviorRepo(t *testing.T, base, edit map[string]string) string {
	t.Helper()
	merged := map[string]string{}
	for k, v := range behaviorBase {
		merged[k] = v
	}
	for k, v := range base {
		merged[k] = v
	}
	return redRepo(t, merged, edit)
}

func measure(t *testing.T, root string) Behavior {
	t.Helper()
	return BehaviorChange(context.Background(), root)
}

func TestBehaviorChange_OneLogicLineCounts(t *testing.T) {
	t.Parallel()
	b := measure(t, behaviorRepo(t, nil, map[string]string{"add.go": redAddFix}))
	assert.Equal(t, 2, b.Lines, "the old and the new line of a one-line fix")
	assert.Empty(t, b.NewFiles)
}

