func write(t *testing.T, root, name, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(name))
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
	require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
}

// block is a repeated run of long code lines.
func block(prefix string) string {
	var b strings.Builder
	for i := 0; i < 7; i++ {
		fmt.Fprintf(&b, "\tresult%d := computeSomethingLong(input%d, options.Threshold, options.Limit)\n", i, i)
	}
	return b.String()
}

func debtRepo(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	out, err := exec.Command("git", "init", "-q", root).CombinedOutput()
	require.NoError(t, err, string(out))
	write(t, root, "a.go", "package a\n\n// TODO handle the empty case\n// TODO(#12) tracked elsewhere\n// FIXME see https://example.com/x\nfunc A() {}\n")
	write(t, root, "tool.py", "# HACK until the API settles\nx = 1\n")
	write(t, root, "lib.rs", "/* XXX: unsafe cast */\nfn f() {}\n")
	write(t, root, "db/q.sql", "-- TODO index this column\nSELECT 1;\n")
	write(t, root, "b.go", "package a\n\nfunc B() {\n"+block("b")+"}\n")
	write(t, root, "c.go", "package a\n\nfunc C() {\n"+block("c")+"}\n")
	write(t, root, "a_test.go", "package a\n\n// TODO not product\n")
	write(t, root, "README.md", "TODO: docs are not product\n")
	write(t, root, "gen.go", "// Code generated by x. DO NOT EDIT.\n\n// TODO generated\npackage a\n")
	write(t, root, ".autopus/x.go", "// TODO harness\n")
	var long strings.Builder
	long.WriteString("package a\n")
	for i := 0; i < 275; i++ {
		fmt.Fprintf(&long, "var v%d = %d\n", i, i)
	}
	write(t, root, "big.go", long.String())
	write(t, root, "small.go", "package a\nvar s = 1\n")
	return root
}

func kinds(items []Item) map[Kind][]string {
	out := map[Kind][]string{}
	for _, it := range items {
		out[it.Kind] = append(out[it.Kind], fmt.Sprintf("%s:%d", it.File, it.Line))
	}
	return out
}

func TestScan_FindsEachKindAndSkipsNonProduct(t *testing.T) {
	root := debtRepo(t)
	items, err := Scan(context.Background(), root, 300)
	require.NoError(t, err)
	k := kinds(items)
	assert.ElementsMatch(t, []string{"a.go:3", "tool.py:1", "lib.rs:1", "db/q.sql:1"}, k[KindMarker], "untracked markers in any language; issue references are tracked")
	assert.Equal(t, []string{"big.go:1"}, k[KindNearLimit])
	require.Len(t, k[KindDuplicate], 1)
	for _, it := range items {
		if it.Kind == KindDuplicate {
			assert.Equal(t, "b.go", it.File)
			assert.Equal(t, []string{"c.go:4"}, it.Also)
		}
	}
}

// A marker moved by code added above it keeps its key.
func TestScan_MovedItemKeepsItsKey(t *testing.T) {
	root := debtRepo(t)
	before, err := Scan(context.Background(), root, 300)
	require.NoError(t, err)
	write(t, root, "a.go", "package a\n\nvar added = 1\nvar more = 2\n\n// TODO handle the empty case\nfunc A() {}\n")
	write(t, root, "c.go", "package a\n\n// moved down\n\nfunc C() {\n"+block("c")+"}\n")
	after, err := Scan(context.Background(), root, 300)
	require.NoError(t, err)
	assert.Empty(t, New(after, Baseline{Items: before}))
}

func TestBaseline_RatchetsOneByOne(t *testing.T) {
	root := debtRepo(t)
	items, err := Scan(context.Background(), root, 300)
	require.NoError(t, err)
	_, _, err = WriteBaseline(root, items, false)
	require.NoError(t, err)
	base, err := LoadBaseline(root)
	require.NoError(t, err)
	assert.Empty(t, New(items, base))

	// Remove one marker and add another: the total is the same, the new one is new.
	write(t, root, "tool.py", "x = 1\n")
	write(t, root, "d.go", "package a\n// FIXME new problem\n")
	items, err = Scan(context.Background(), root, 300)
	require.NoError(t, err)
	block, warn := Blocking(New(items, base))
	require.Len(t, block, 1)
	assert.Equal(t, "d.go", block[0].File)
	assert.Empty(t, warn)
	_, _, err = WriteBaseline(root, items, false)
	assert.ErrorIs(t, err, ErrNewDebt, "a rewrite does not quietly accept new debt")

	write(t, root, "d.go", "package a\n")
	items, err = Scan(context.Background(), root, 300)
	require.NoError(t, err)
	_, removed, err := WriteBaseline(root, items, false)
	require.NoError(t, err)
	assert.Equal(t, 1, removed, "the cleaned-up marker leaves the baseline")
	_, err = LoadBaseline(t.TempDir())
	assert.ErrorIs(t, err, ErrNoBaseline)
}

func TestCleanupBrief_LargestFirst(t *testing.T) {
	items := []Item{{Kind: KindMarker, File: "a.go", Line: 3, Lines: 1, Text: "TODO x"},
		{Kind: KindDuplicate, File: "b.go", Line: 4, Lines: 14, Also: []string{"c.go:4"}},
		{Kind: KindNearLimit, File: "big.go", Line: 1, Lines: 275, Text: "275 of 300 lines"}}
	got := CleanupBrief(items, 5)
	assert.Less(t, strings.Index(got, "big.go"), strings.Index(got, "b.go:4"))
	assert.Less(t, strings.Index(got, "b.go:4"), strings.Index(got, "a.go:3"))
	assert.Contains(t, got, "auto debt baseline")
	assert.Equal(t, "No technical-debt items to clean up.\n", CleanupBrief(nil, 5))
}

// A scan past its deadline keeps what it read and says it did not finish.
func TestScanWith_DeadlineIndexesOverSeveralScans(t *testing.T) {
	root := debtRepo(t)
	_, err := ScanWith(context.Background(), root, Options{Deadline: time.Now().Add(-time.Second)})
	assert.ErrorIs(t, err, ErrIncomplete)
	items, err := ScanWith(context.Background(), root, Options{})
	require.NoError(t, err)
	assert.NotEmpty(t, items)
}
