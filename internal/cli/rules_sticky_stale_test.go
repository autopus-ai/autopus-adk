package cli

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func withStickyBinaryVersion(t *testing.T, v string) {
	t.Helper()
	prev := stickyBinaryVersion
	stickyBinaryVersion = func() string { return v }
	t.Cleanup(func() { stickyBinaryVersion = prev })
}

func writeClaudeManifest(t *testing.T, dir, generator string) {
	t.Helper()
	body := `{"version":"1.0.0","platform":"claude-code","generated_at":"2026-11-12T05:29:00+09:00",`
	if generator != "" {
		body += `"generator":"` + generator + `",`
	}
	body += `"files":{}}`
	path := filepath.Join(dir, ".autopus", "claude-code-manifest.json")
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(body), 0o644))
}

func TestStickyStaleSurfaceAlert(t *testing.T) {
	cases := []struct {
		name, running, generator, want string
		noManifest                     bool
	}{
		{name: "older generator", running: "0.51.8", generator: "0.51.7",
			want: "Harness alert: the installed rules and skills were generated by auto 0.51.7, but this project now runs auto 0.51.8. " +
				"The installed instructions may be out of date: tell the user and suggest `auto update` before relying on them."},
		{name: "pre-field manifest", running: "0.51.8", generator: "",
			want: "Harness alert: the installed rules and skills were generated by an older auto, but this project now runs auto 0.51.8. " +
				"The installed instructions may be out of date: tell the user and suggest `auto update` before relying on them."},
		{name: "same version", running: "0.51.8", generator: "0.51.8", want: ""},
		{name: "dev build", running: "dev", generator: "0.51.7", want: ""},
		{name: "dirty build", running: "0.51.8-dirty", generator: "0.51.7", want: ""},
		{name: "no manifest", running: "0.51.8", noManifest: true, want: ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			if !tc.noManifest {
				writeClaudeManifest(t, dir, tc.generator)
			}
			withStickyBinaryVersion(t, tc.running)
			assert.Equal(t, tc.want, stickyStaleSurfaceAlert(dir))
		})
	}
}

// The alert reaches the session through the real UserPromptSubmit command and
// leaves the output unchanged once the surface is regenerated.
func TestRulesSticky_StaleSurfaceAlertThroughHook(t *testing.T) {
	dir := stickyProjectRoot(t, "STALE-BODY")
	withStickyBinaryVersion(t, "0.51.8")

	writeClaudeManifest(t, dir, "0.51.7")
	stale, _ := runRulesSticky(t, dir, cliStickyPayload("S-stale", "one"))
	assert.Contains(t, stickyContext(t, stale), "generated by auto 0.51.7, but this project now runs auto 0.51.8")

	withStickyBinaryVersion(t, "0.51.7")
	fresh, _ := runRulesSticky(t, dir, cliStickyPayload("S-fresh", "one"))
	assert.NotContains(t, fresh, "Harness alert")
}
